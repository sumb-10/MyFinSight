"""2026-11 시나리오 QA 라운드 25 (091~095) 회귀 테스트."""

from __future__ import annotations


def test_bl_optimizer_keeps_view_directions_when_rounding_makes_a_sector_hair_over_its_cap():
    """093 (라운드 25): 저장 비중(소수 6자리 버림)을 합계에 다시 맞추자 섹터 상한 40% 에 닿아 있던 산업재가 0.4000002 가 됐고,
    산업재 세 종목이 모두 오름 뷰(하한 = 기준 비중)라 풀 수 없는 문제가 돼 방향 경계 없이 다시 풀었다 — LGES 오름 뷰인데 −7.35%p.
    (라운드 22 의 해 검사가 1e-7 로 빡빡해 드러났다.) 섹터 상한에 반올림 크기의 여유를 둔다."""
    import numpy as np

    from backend.analysis.m4_portfolio import math as P

    cov = np.array([[0.411481, 0.167172, 0.204662, 0.317398, 0.182748, 0.07884], [0.167172, 0.255211, 0.127477, 0.169399, 0.126701, 0.057263],
                    [0.204662, 0.127477, 0.216774, 0.218347, 0.146253, 0.047548], [0.317398, 0.169399, 0.218347, 0.508649, 0.183501, 0.065878],
                    [0.182748, 0.126701, 0.146253, 0.183501, 0.209658, 0.05621], [0.07884, 0.057263, 0.047548, 0.065878, 0.05621, 0.38457]])  # fmt: skip
    mu = np.array([0.48687, 0.326669, 0.355668, 0.521108, 0.32711, 0.237771])
    wb = np.array([0.122056, 0.205624, 0.168163, 0.10978, 0.226866, 0.167508])  # 산업재(20) 합 0.399999, 전체 0.999997
    sec = ["20", "10", "20", "20", "15", "15"]
    vd = [1, -1, 1, 1, -1, 0]
    w, active = P.optimize_utility(mu, cov, 1.9773, wb, 0.25, 0.4, sec, 1 / 12, 1.0, min_weight=0.01, view_dir=vd)
    d = w - wb / wb.sum()
    assert all(v * x >= -1e-6 for v, x in zip(vd, d))  # 어느 종목도 뷰와 반대로 움직이지 않는다
    assert any(a.startswith("view_hold") for a in active)
